import { useState, useMemo, useCallback } from 'react';
import { Link } from 'react-router-dom';
import { Icon } from '@iconify/react';
import { PACKS, TYPE_LABELS, TYPE_COLORS } from '../data/packs';
import {
  STACK_TEMPLATES,
  COMPAT_GRAPH,
  areCompatible,
  suggestPacks,
  packRuntime,
  packScopes,
  parseInstalls,
  formatInstalls,
} from '../data/stackTemplates';
import { useStack } from '../hooks/useStack';
import ScrollReveal from '../components/ScrollReveal';

const CATEGORIES = ['all', 'logic', 'ui', 'automation', 'creative', 'provider'];
const BY_SLUG = Object.fromEntries(PACKS.map(p => [p.slug, p]));

// A tiny "copied ✓" button that reverts after a moment.
function CopyButton({ text, label = 'Copy', className = '' }) {
  const [done, setDone] = useState(false);
  const copy = useCallback(async () => {
    try {
      await navigator.clipboard.writeText(text);
    } catch {
      // Fallback for older/embedded browsers without the async clipboard API.
      const ta = document.createElement('textarea');
      ta.value = text;
      ta.style.position = 'fixed';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      try { document.execCommand('copy'); } catch { /* ignore */ }
      document.body.removeChild(ta);
    }
    setDone(true);
    setTimeout(() => setDone(false), 1600);
  }, [text]);

  return (
    <button
      onClick={copy}
      className={`inline-flex items-center gap-1.5 text-[11px] font-medium rounded-md px-2.5 py-1.5 border transition-colors ${
        done
          ? 'border-green-500/30 bg-green-500/10 text-green-400'
          : 'border-white/10 text-neutral-400 hover:text-white hover:bg-white/5'
      } ${className}`}
    >
      <Icon icon={done ? 'solar:check-read-linear' : 'solar:copy-linear'} width={13} />
      {done ? 'Copied' : label}
    </button>
  );
}

export default function StackBuilder() {
  const { slugs, has, toggle, remove, clear, set } = useStack();
  const [activeFilter, setActiveFilter] = useState('all');
  const [search, setSearch] = useState('');
  const [shareCopied, setShareCopied] = useState(false);

  const selectedPacks = useMemo(
    () => slugs.map(s => BY_SLUG[s]).filter(Boolean),
    [slugs],
  );

  const filtered = useMemo(() => {
    const q = search.trim().toLowerCase();
    return PACKS.filter(p => {
      const matchesType = activeFilter === 'all' || p.type === activeFilter;
      const matchesSearch = !q || p.name.toLowerCase().includes(q) || p.desc.toLowerCase().includes(q);
      return matchesType && matchesSearch;
    });
  }, [activeFilter, search]);

  // ── Aggregate stats over the selected stack ──
  const summary = useMemo(() => {
    const typeCounts = {};
    const runtimes = new Set();
    const scopes = new Set();
    let installs = 0;
    for (const p of selectedPacks) {
      typeCounts[p.type] = (typeCounts[p.type] || 0) + 1;
      runtimes.add(packRuntime(p));
      for (const s of packScopes(p)) scopes.add(s);
      installs += parseInstalls(p.installs);
    }
    return {
      typeCounts,
      runtimes: [...runtimes],
      scopes: [...scopes].sort(),
      installs,
      verified: selectedPacks.filter(p => p.verified).length,
    };
  }, [selectedPacks]);

  // ── Compatibility analysis: which selected pairs are known-compatible, and
  // which selected packs are "islands" with no declared link to the rest. ──
  const compat = useMemo(() => {
    const links = [];
    const linkedSlugs = new Set();
    for (let i = 0; i < selectedPacks.length; i++) {
      for (let j = i + 1; j < selectedPacks.length; j++) {
        const a = selectedPacks[i];
        const b = selectedPacks[j];
        if (areCompatible(a.slug, b.slug)) {
          links.push([a, b]);
          linkedSlugs.add(a.slug);
          linkedSlugs.add(b.slug);
        }
      }
    }
    const islands = selectedPacks.filter(
      p => !linkedSlugs.has(p.slug) && (COMPAT_GRAPH[p.slug]?.size || 0) > 0,
    );
    return { links, islands };
  }, [selectedPacks]);

  const suggestions = useMemo(() => suggestPacks(slugs, 4), [slugs]);

  // ── Generated artifacts ──
  const installCmd = useMemo(
    () => (slugs.length ? `lp install ${slugs.join(' ')}` : 'lp install <pack>...'),
    [slugs],
  );

  const manifest = useMemo(() => {
    if (!selectedPacks.length) return '';
    const lines = [
      '# stack.yaml — generated by Logic Packs Stack Builder',
      'name: my-stack',
      'version: 0.1.0',
      `runtime:${summary.runtimes.length ? ' ' : ''}${summary.runtimes.map(r => `\n  - ${r}`).join('')}`,
      'packs:',
    ];
    for (const p of selectedPacks) {
      lines.push(`  - pack: ${p.slug}`);
      lines.push(`    version: "${p.version.replace(/^v/, '')}"`);
      lines.push(`    type: ${p.type}`);
    }
    if (summary.scopes.length) {
      lines.push('scopes:');
      for (const s of summary.scopes) lines.push(`  - ${s}`);
    }
    return lines.join('\n');
  }, [selectedPacks, summary]);

  const shareUrl = useMemo(() => {
    if (typeof window === 'undefined') return '';
    const base = `${window.location.origin}${window.location.pathname}`;
    return slugs.length ? `${base}?stack=${slugs.join(',')}` : base;
  }, [slugs]);

  const copyShare = useCallback(async () => {
    try {
      await navigator.clipboard.writeText(shareUrl);
    } catch { /* ignore */ }
    // Reflect the current stack in the address bar without a navigation.
    try {
      window.history.replaceState(null, '', slugs.length ? `?stack=${slugs.join(',')}` : window.location.pathname);
    } catch { /* ignore */ }
    setShareCopied(true);
    setTimeout(() => setShareCopied(false), 1600);
  }, [shareUrl, slugs]);

  const applyTemplate = useCallback(t => set(t.packs), [set]);

  const empty = selectedPacks.length === 0;

  return (
    <>
      {/* ── Hero ── */}
      <section className="pt-14 border-b border-white/[0.06]">
        <div className="max-w-[1440px] mx-auto px-6 md:px-8 py-16 md:py-20">
          <ScrollReveal>
            <div className="flex items-center gap-2 mb-4">
              <div className="w-8 h-8 rounded-lg bg-green-500/10 border border-green-500/20 flex items-center justify-center">
                <Icon icon="solar:layers-minimalistic-linear" className="text-green-500 text-lg" />
              </div>
              <span className="text-xs uppercase tracking-[0.2em] text-green-500/80 font-mono font-medium">Stack Builder</span>
            </div>
          </ScrollReveal>
          <ScrollReveal><h1 className="text-4xl md:text-6xl font-semibold text-white tracking-tight mb-4">Compose your stack</h1></ScrollReveal>
          <ScrollReveal>
            <p className="text-neutral-500 text-base md:text-lg max-w-xl mb-8">
              Pick the packs your app needs. We check compatibility, aggregate permissions, and generate a ready-to-run manifest and install command — no backend required.
            </p>
          </ScrollReveal>

          {/* Templates */}
          <ScrollReveal>
            <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3">
              {STACK_TEMPLATES.map(t => (
                <button
                  key={t.id}
                  onClick={() => applyTemplate(t)}
                  className="text-left p-4 rounded-xl border border-white/[0.06] bg-[#0f0f0f] hover:bg-[#131313] hover:border-white/10 transition-all group"
                >
                  <div className="flex items-center gap-2 mb-2">
                    <Icon icon={t.icon} className={`${t.accent} text-lg`} />
                    <span className="text-white text-sm font-medium group-hover:text-green-500 transition-colors">{t.name}</span>
                  </div>
                  <p className="text-neutral-500 text-[11px] leading-relaxed mb-2">{t.desc}</p>
                  <span className="text-neutral-600 text-[10px] font-mono">{t.packs.length} packs →</span>
                </button>
              ))}
            </div>
          </ScrollReveal>
        </div>
      </section>

      {/* ── Builder ── */}
      <section>
        <div className="max-w-[1440px] mx-auto px-6 md:px-8 py-12 grid grid-cols-1 lg:grid-cols-[1fr_400px] gap-8 items-start">
          {/* Palette */}
          <div>
            <div className="flex flex-col sm:flex-row gap-3 mb-6">
              <div className="relative flex-1">
                <Icon icon="solar:magnifer-linear" className="absolute left-3 top-1/2 -translate-y-1/2 text-neutral-600" width={16} />
                <input
                  type="text"
                  placeholder="Search packs to add..."
                  value={search}
                  onChange={e => setSearch(e.target.value)}
                  className="w-full bg-[#111] border border-white/[0.06] rounded-lg pl-9 pr-4 py-2.5 text-sm text-white placeholder:text-neutral-700 focus:outline-none focus:border-green-500/30 transition-colors"
                />
              </div>
              <div className="flex gap-2 flex-wrap">
                {CATEGORIES.map(c => (
                  <button
                    key={c}
                    onClick={() => setActiveFilter(c)}
                    className={`px-3 py-2 rounded-lg text-[11px] font-medium uppercase tracking-wider transition-all border ${
                      activeFilter === c ? 'bg-white text-black border-white' : 'border-white/[0.06] text-neutral-500 hover:text-white hover:bg-white/5'
                    }`}
                  >
                    {c === 'all' ? 'All' : TYPE_LABELS[c]}
                  </button>
                ))}
              </div>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              {filtered.map(pack => {
                const inStack = has(pack.slug);
                return (
                  <div
                    key={pack.slug}
                    className={`p-4 rounded-xl border transition-all ${
                      inStack ? 'border-green-500/30 bg-green-500/[0.04]' : 'border-white/[0.06] bg-[#0f0f0f] hover:border-white/10'
                    }`}
                  >
                    <div className="flex items-start justify-between mb-2 gap-2">
                      <div className="flex items-center gap-3 min-w-0">
                        <div className={`w-9 h-9 shrink-0 rounded-lg ${pack.bgColor} border ${pack.borderColor} flex items-center justify-center`}>
                          <Icon icon={pack.icon} className={`${pack.iconColor} text-base`} />
                        </div>
                        <div className="min-w-0">
                          <Link to={`/pack/${pack.slug}`} className="text-white text-sm font-medium hover:text-green-500 transition-colors block truncate">{pack.name}</Link>
                          <span className="text-neutral-600 text-[10px] font-mono">{pack.version} · {pack.installs}</span>
                        </div>
                      </div>
                      <button
                        onClick={() => toggle(pack.slug)}
                        aria-label={inStack ? `Remove ${pack.name} from stack` : `Add ${pack.name} to stack`}
                        className={`shrink-0 w-7 h-7 rounded-md flex items-center justify-center border transition-colors ${
                          inStack ? 'border-green-500/40 bg-green-500/15 text-green-400 hover:bg-green-500/25' : 'border-white/10 text-neutral-400 hover:text-white hover:bg-white/5'
                        }`}
                      >
                        <Icon icon={inStack ? 'solar:check-read-linear' : 'solar:add-circle-linear'} width={16} />
                      </button>
                    </div>
                    <p className="text-neutral-500 text-[11px] leading-relaxed line-clamp-2">{pack.desc}</p>
                    <div className="mt-2">
                      <span className={`px-2 py-0.5 rounded text-[10px] font-medium border ${TYPE_COLORS[pack.type]}`}>{TYPE_LABELS[pack.type]}</span>
                    </div>
                  </div>
                );
              })}
            </div>
            {filtered.length === 0 && (
              <div className="text-center py-16">
                <Icon icon="solar:box-minimalistic-linear" className="text-neutral-700 text-4xl mx-auto mb-3" />
                <p className="text-neutral-600 text-sm">No packs match your search.</p>
              </div>
            )}
          </div>

          {/* Summary panel (sticky on desktop) */}
          <aside className="lg:sticky lg:top-20 space-y-4">
            <div className="rounded-2xl border border-white/[0.08] bg-[#0f0f0f] overflow-hidden">
              <div className="flex items-center justify-between px-5 py-4 border-b border-white/[0.06]">
                <div className="flex items-center gap-2">
                  <Icon icon="solar:layers-minimalistic-bold" className="text-green-500" width={16} />
                  <h2 className="text-white text-sm font-semibold">Your Stack</h2>
                  <span className="text-neutral-600 text-xs font-mono">({selectedPacks.length})</span>
                </div>
                {!empty && (
                  <button onClick={clear} className="text-[11px] text-neutral-500 hover:text-red-400 transition-colors">Clear</button>
                )}
              </div>

              {empty ? (
                <div className="px-5 py-10 text-center">
                  <Icon icon="solar:box-minimalistic-linear" className="text-neutral-700 text-3xl mx-auto mb-3" />
                  <p className="text-neutral-500 text-xs leading-relaxed">Add packs from the left, or start from a template above. Your stack is saved to this browser automatically.</p>
                </div>
              ) : (
                <div className="p-5 space-y-5">
                  {/* Selected packs */}
                  <div className="space-y-2">
                    {selectedPacks.map(p => (
                      <div key={p.slug} className="flex items-center gap-2.5 group">
                        <div className={`w-7 h-7 shrink-0 rounded-md ${p.bgColor} border ${p.borderColor} flex items-center justify-center`}>
                          <Icon icon={p.icon} className={`${p.iconColor} text-sm`} />
                        </div>
                        <span className="text-neutral-300 text-xs flex-1 truncate">{p.name}</span>
                        <span className={`px-1.5 py-0.5 rounded text-[9px] font-medium border ${TYPE_COLORS[p.type]}`}>{TYPE_LABELS[p.type]}</span>
                        <button onClick={() => remove(p.slug)} aria-label={`Remove ${p.name}`} className="text-neutral-600 hover:text-red-400 transition-colors">
                          <Icon icon="solar:close-circle-linear" width={15} />
                        </button>
                      </div>
                    ))}
                  </div>

                  {/* Stats */}
                  <div className="grid grid-cols-3 gap-2">
                    <div className="rounded-lg border border-white/[0.06] bg-[#0a0a0a] px-2 py-2.5 text-center">
                      <div className="text-white text-lg font-semibold leading-none">{selectedPacks.length}</div>
                      <div className="text-neutral-600 text-[9px] uppercase tracking-wider mt-1">Packs</div>
                    </div>
                    <div className="rounded-lg border border-white/[0.06] bg-[#0a0a0a] px-2 py-2.5 text-center">
                      <div className="text-white text-lg font-semibold leading-none">{formatInstalls(summary.installs)}</div>
                      <div className="text-neutral-600 text-[9px] uppercase tracking-wider mt-1">Installs</div>
                    </div>
                    <div className="rounded-lg border border-white/[0.06] bg-[#0a0a0a] px-2 py-2.5 text-center">
                      <div className="text-white text-lg font-semibold leading-none">{summary.runtimes.length}</div>
                      <div className="text-neutral-600 text-[9px] uppercase tracking-wider mt-1">Runtimes</div>
                    </div>
                  </div>

                  {/* Compatibility */}
                  <div>
                    <span className="font-mono text-neutral-600 text-[10px] block mb-2">/// Compatibility</span>
                    {compat.links.length > 0 && (
                      <div className="flex items-center gap-1.5 text-green-400/90 text-[11px] mb-2">
                        <Icon icon="solar:check-circle-bold" width={13} />
                        <span>{compat.links.length} verified compatible {compat.links.length === 1 ? 'pairing' : 'pairings'}</span>
                      </div>
                    )}
                    {compat.islands.length > 0 ? (
                      <div className="flex items-start gap-1.5 text-amber-400/90 text-[11px]">
                        <Icon icon="solar:info-circle-linear" width={13} className="mt-0.5 shrink-0" />
                        <span>{compat.islands.map(p => p.name).join(', ')} {compat.islands.length === 1 ? 'has' : 'have'} no declared link to the rest — they should still compose, just untested together.</span>
                      </div>
                    ) : compat.links.length === 0 ? (
                      <p className="text-neutral-600 text-[11px]">Add two or more related packs to see compatibility links.</p>
                    ) : (
                      <div className="flex items-center gap-1.5 text-green-400/90 text-[11px]">
                        <Icon icon="solar:link-round-linear" width={13} />
                        <span>Every pack links to the stack.</span>
                      </div>
                    )}
                  </div>

                  {/* Permissions */}
                  {summary.scopes.length > 0 && (
                    <div>
                      <span className="font-mono text-neutral-600 text-[10px] block mb-2">/// Combined permissions</span>
                      <div className="flex flex-wrap gap-1.5">
                        {summary.scopes.map(s => (
                          <span key={s} className="px-2 py-0.5 rounded bg-white/[0.04] border border-white/[0.06] text-neutral-400 text-[10px] font-mono">{s}</span>
                        ))}
                      </div>
                    </div>
                  )}

                  {/* Install command */}
                  <div>
                    <div className="flex items-center justify-between mb-2">
                      <span className="font-mono text-neutral-600 text-[10px]">/// Install</span>
                      <CopyButton text={installCmd} />
                    </div>
                    <div className="rounded-lg border border-white/[0.06] bg-[#0a0a0a] px-3 py-2.5 overflow-x-auto">
                      <code className="text-[11px] font-mono text-green-400 whitespace-pre">$ {installCmd}</code>
                    </div>
                  </div>

                  {/* Manifest */}
                  <div>
                    <div className="flex items-center justify-between mb-2">
                      <span className="font-mono text-neutral-600 text-[10px]">/// stack.yaml</span>
                      <CopyButton text={manifest} />
                    </div>
                    <pre className="rounded-lg border border-white/[0.06] bg-[#0a0a0a] px-3 py-2.5 overflow-x-auto text-[10.5px] font-mono text-neutral-400 leading-relaxed max-h-56">{manifest}</pre>
                  </div>

                  {/* Share */}
                  <button
                    onClick={copyShare}
                    className={`w-full inline-flex items-center justify-center gap-2 rounded-lg px-4 py-2.5 text-xs font-semibold transition-colors ${
                      shareCopied ? 'bg-green-500/15 text-green-400 border border-green-500/30' : 'bg-white text-black hover:bg-neutral-200'
                    }`}
                  >
                    <Icon icon={shareCopied ? 'solar:check-read-linear' : 'solar:link-round-linear'} width={14} />
                    {shareCopied ? 'Share link copied' : 'Copy share link'}
                  </button>
                </div>
              )}
            </div>

            {/* Suggestions */}
            {suggestions.length > 0 && (
              <div className="rounded-2xl border border-white/[0.08] bg-[#0f0f0f] p-5">
                <span className="font-mono text-neutral-600 text-[10px] block mb-3">/// Works well with</span>
                <div className="space-y-2">
                  {suggestions.map(({ pack, matches }) => (
                    <div key={pack.slug} className="flex items-center gap-2.5">
                      <div className={`w-7 h-7 shrink-0 rounded-md ${pack.bgColor} border ${pack.borderColor} flex items-center justify-center`}>
                        <Icon icon={pack.icon} className={`${pack.iconColor} text-sm`} />
                      </div>
                      <div className="flex-1 min-w-0">
                        <span className="text-neutral-300 text-xs block truncate">{pack.name}</span>
                        <span className="text-neutral-600 text-[10px]">compatible with {matches} in your stack</span>
                      </div>
                      <button
                        onClick={() => toggle(pack.slug)}
                        aria-label={`Add ${pack.name} to stack`}
                        className="shrink-0 w-6 h-6 rounded-md border border-white/10 text-neutral-400 hover:text-white hover:bg-white/5 flex items-center justify-center transition-colors"
                      >
                        <Icon icon="solar:add-circle-linear" width={14} />
                      </button>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </aside>
        </div>
      </section>
    </>
  );
}
